#!/usr/bin/env python3
"""Write university/build/PROGRESS.md: which courses are committed, which are pending.

A course counts as done when its NOTES.md is in git (commit_course.sh adds it last).
Usage: python3 university/build/progress.py [--staged] [--next N]
  --staged  also count files staged in the index (used by commit_course.sh)
  --next N  print the next N pending course codes and exit
"""
import pathlib, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
UNI = ROOT / "university"
queue = [l.split() for l in (UNI / "build/QUEUE.txt").read_text().splitlines()
         if l.strip() and not l.startswith("#")]
tracked = set(subprocess.run(["git", "ls-files", "university/chapters"], cwd=ROOT,
                             capture_output=True, text=True).stdout.split())
if "--staged" not in sys.argv:
    # only what is in HEAD
    tracked = set(subprocess.run(["git", "ls-tree", "-r", "--name-only", "HEAD",
                                  "university/chapters"], cwd=ROOT,
                                 capture_output=True, text=True).stdout.split())

def done(c):
    return f"university/chapters/{c}/NOTES.md" in tracked

def nchap(c):
    return sum(1 for f in tracked if f.startswith(f"university/chapters/{c}/") and f.endswith(".html"))

pending = [c for line in queue for c in line if not done(c)]
if "--next" in sys.argv:
    n = int(sys.argv[sys.argv.index("--next") + 1])
    print(" ".join(pending[:n]))
    sys.exit(0)

all_c = [c for line in queue for c in line]
lines = ["# Build progress", "",
         "Generated by `university/build/progress.py`; a course is *done* when it is committed.",
         "See `RESUME.md` for how to continue the build.", "",
         f"**{len(all_c) - len(pending)} of {len(all_c)} units done (courses, bridges, mega projects), "
         f"{sum(nchap(c) for c in all_c)} chapters committed.**", "",
         "| Courses (one faculty group per row) | Status |", "|---|---|"]
for line in queue:
    lines.append("| " + " ".join(line) + " | " +
                 " ".join(f"{c} {'✓' if done(c) else '○'}" for c in line) + " |")
lines += ["", "The queue holds the 87 courses, then bridge chapters BR-01..10 and mega projects MP1..8. "
          "Still to do after the queue: glossary link fixes, final "
          "`build.py --check`, commit UNIVERSITY.html, mark PR ready.", ""]
(UNI / "build/PROGRESS.md").write_text("\n".join(lines))
print(f"{len(pending)} pending: {' '.join(pending)}")
