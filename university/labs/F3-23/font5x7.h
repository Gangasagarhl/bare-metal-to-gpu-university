// Returns the 7 rows of 'c' as 5-bit masks (bit 4 = leftmost pixel).
inline void rows_of(char c, uint8_t out[7])
{
    if (c >= 'a' && c <= 'z') {
        c = static_cast<char>(c - 'a' + 'A');
    }
    const Glyph* g = nullptr;
    const Glyph* unknown = nullptr;
    for (const Glyph& x : kGlyphs) {
        if (x.ch == c) {
            g = &x;
        }
        if (x.ch == '?') {
            unknown = &x;
        }
    }
    if (g == nullptr) {
        g = unknown;
    }
    for (int r = 0; r < 7; ++r) {
        uint8_t bits = 0;
        for (int col = 0; col < 5; ++col) {
            bits = static_cast<uint8_t>((bits << 1) | (g->rows[r][col] == '#' ? 1 : 0));
        }
        out[r] = bits;
    }
}

