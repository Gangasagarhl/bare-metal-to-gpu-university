#include <iostream>

int main()
{
    std::cout << "3 - 7 = " << 3 - 7 << "; -4 + 2 = " << -4 + 2 << "\n";
    std::cout << "-3 + 8 = " << -3 + 8 << "; 5 - (-3) = " << 5 - (-3) << "; 5 - 3 = " << 5 - 3 << "\n";
    std::cout << "-2 - 3 = " << -2 - 3 << "; -6 + 6 = " << -6 + 6 << "\n";
    std::cout << "-5 < -2 is " << (-5 < -2 ? "true" : "false") << "; -1 > -10 is " << (-1 > -10 ? "true" : "false") << "\n";
    std::cout << "distance from -4 to 3 = " << 3 - (-4) << "\n";
    std::cout << "4 + (-6) = " << 4 + (-6) << "; 4 - 6 = " << 4 - 6 << "\n";
    std::cout << "-2 - (-5) = " << -2 - (-5) << "; -2 + 5 = " << -2 + 5 << "\n";
    std::cout << "money: 0 - 4 = " << 0 - 4 << "; -4 + 10 = " << -4 + 10 << "\n";
    std::cout << "-1 + 1 = " << -1 + 1 << "; 0 - 1 = " << 0 - 1 << "\n";
    std::cout << "3 x (-2) = " << 3 * (-2) << "; (-3) x (-2) = " << (-3) * (-2) << "\n";
    std::cout << "-7 / 2 in C++ int = " << -7 / 2 << "\n";
    std::cout << "floor -2 to floor 4 = " << 4 - (-2) << " floors\n";
    std::cout << "-8 + 3 = " << -8 + 3 << "; 1 - 9 = " << 1 - 9 << "\n";
    std::cout << "lowest of 2, -6, 0, -1 is " << -6 << "; order: -6 < -1 < 0 < 2\n";
    std::cout << "3 + (-3) = " << 3 + (-3) << "; -7.0 / 2 = " << -7.0 / 2 << "\n";
    std::cout << "5 + 3 = " << 5 + 3 << "; 7 - 3 = " << 7 - 3 << "; -4 - 3 = " << -4 - 3 << "\n";
    std::cout << "3 x 2, 3 x 1, 3 x 0, 3 x -1, 3 x -2: " << 3 * 2 << " " << 3 * 1 << " " << 3 * 0 << " " << 3 * -1
              << " " << 3 * -2 << "\n";
    std::cout << "-3 x 2, -3 x 1, -3 x 0, -3 x -1, -3 x -2: " << -3 * 2 << " " << -3 * 1 << " " << -3 * 0 << " "
              << -3 * -1 << " " << -3 * -2 << "\n";
    return 0;
}
